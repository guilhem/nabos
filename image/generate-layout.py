#!/usr/bin/env python3
"""Generate checked-in boot and image settings from the production layout."""
import argparse
import json
from pathlib import Path
import shlex


def outputs(layout):
    def size(value):
        for suffix, unit in (("G", 1 << 30), ("M", 1 << 20), ("K", 1 << 10)):
            if value % unit == 0:
                return f"{value // unit}{suffix}"
        return str(value)

    def partition(name, offset, length=None, kind=None, image=None, bootable=False):
        fields = []
        if kind is None:
            fields.append("in-partition-table = false")
        else:
            fields.append(f"partition-type = {kind}")
        if bootable:
            fields.append("bootable = true")
        fields.append(f"offset = {size(offset)}")
        if length is not None:
            fields.append(f"size = {size(length)}")
        if image:
            fields.append(f'image = "{image}"')
        return f"\tpartition {name} {{\n" + "".join(f"\t\t{field}\n" for field in fields) + "\t}\n"

    l = layout
    header = "# Generated by image/generate-layout.py from image/layout.json; do not edit.\n"
    genimage = header + "# Slot B ships empty; the initrd grows data to the end of the card.\nimage sdcard.img {\n\thdimage {\n\t}\n\n"
    genimage += "\n".join([
        partition("uboot-env", l["env_offset"], image="uboot.env"),
        partition("uboot-env-redund", l["env_offset_redund"], image="uboot.env"),
        partition("boot", l["boot_primary_offset"], l["boot_size"], l["boot_partition_type"], "boot.vfat", True),
        partition("boot-redund", l["boot_secondary_offset"], l["boot_size"], image="boot.vfat"),
        partition("rootfs-a", l["root_a_offset"], l["root_size"], l["root_partition_type"], "rootfs.ext4"),
        partition("rootfs-b", l["root_b_offset"], l["root_size"], l["root_partition_type"]),
        partition("data", l["data_offset"], l["data_size"], l["data_partition_type"], "data.ext4"),
    ]) + "}\n"
    fw_env = header + "".join(
        f'{l["disk"]} {offset:#x} {l["env_size"]:#x}\n'
        for offset in (l["env_offset"], l["env_offset_redund"])
    )
    pairs = " ".join(f"{l[key]},{l[key]}" for key in ("root_a_partition", "root_b_partition"))
    uboot = header + f'''# CONFIG_ENV_IS_IN_FAT is not set
CONFIG_ENV_IS_IN_MMC=y
CONFIG_ENV_REDUNDANT=y
CONFIG_ENV_SIZE={l["env_size"]:#x}
CONFIG_ENV_OFFSET={l["env_offset"]:#x}
CONFIG_ENV_OFFSET_REDUND={l["env_offset_redund"]:#x}
CONFIG_ENV_MMC_DEVICE_INDEX={l["mmc_device"]}
CONFIG_BOOTMETH_RAUC=y
CONFIG_BOOTMETH_RAUC_PARTITIONS="{pairs}"
CONFIG_BOOTMETH_RAUC_BOOT_ORDER="{l["boot_order"]}"
CONFIG_BOOTMETH_RAUC_DEFAULT_TRIES={l["boot_attempts"]}
CONFIG_BOOTMETH_RAUC_RESET_ALL_ZERO_TRIES=y
'''
    shell = header + "# shellcheck shell=sh disable=SC2034\n" + "".join(
        f"NABOS_{key.upper()}={shlex.quote(str(value))}\n" for key, value in l.items()
    )
    env = header + f'BOOT_ORDER={l["boot_order"]}\nBOOT_A_LEFT={l["boot_attempts"]}\nBOOT_B_LEFT=0\n'
    boot_env = header + f'''nabos_target=@TARGET@
nabos_dtb=@DTB@
nabos_root_a_part={l["root_a_partition"]}
nabos_root_b_part={l["root_b_partition"]}
nabos_boot_attempts={l["boot_attempts"]}
'''
    return {
        "genimage.cfg": genimage,
        "rootfs/etc/fw_env.config": fw_env,
        "boot/layout.config": uboot,
        "boot/layout.env": env,
        "boot/boot.env.in": boot_env,
        "layout.sh": shell,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    layout = json.loads((directory / "layout.json").read_text())
    # genimage assigns MBR numbers to visible partitions in declaration order.
    assert [layout[key] for key in ("boot_partition", "root_a_partition", "root_b_partition", "data_partition")] == [1, 2, 3, 4]
    assert layout["boot_region_start"] == layout["boot_primary_offset"]
    assert layout["boot_secondary_offset"] == layout["boot_primary_offset"] + layout["boot_size"]
    assert layout["boot_region_size"] == 2 * layout["boot_size"]
    assert layout["root_a_offset"] == layout["boot_region_start"] + layout["boot_region_size"]
    assert layout["root_b_offset"] == layout["root_a_offset"] + layout["root_size"]
    assert layout["data_offset"] == layout["root_b_offset"] + layout["root_size"]
    ranges = [
        (layout["env_offset"], layout["env_size"]),
        (layout["env_offset_redund"], layout["env_size"]),
        (layout["boot_primary_offset"], layout["boot_size"]),
        (layout["boot_secondary_offset"], layout["boot_size"]),
        (layout["root_a_offset"], layout["root_size"]),
        (layout["root_b_offset"], layout["root_size"]),
        (layout["data_offset"], layout["data_size"]),
    ]
    sector = layout["sector_size"]
    assert sector > 0
    for start, length in ranges:
        assert start >= sector and length > 0
        assert start % sector == 0 and length % sector == 0
    for (start, length), (following, _) in zip(ranges, ranges[1:]):
        assert start + length <= following
    stale = []
    for name, content in outputs(layout).items():
        path = directory / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.write_text(content)
    if stale:
        parser.exit(1, "Stale layout outputs: " + ", ".join(stale) + "; run python3 image/generate-layout.py\n")


if __name__ == "__main__":
    main()
